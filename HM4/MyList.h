#pragma once // компілятор підключає файл лише один раз

#include<iostream> // потрібно для cout
#include<fstream>  // потрібно для ofstream (запис у файл)
using namespace std; // щоб не писати std:: постійно

template <typename MyData> class MyList // шаблонний клас - MyData буде замінено на реальний тип при використанні (People, int, ...)
{
private: // внутрішні деталі реалізації, приховані від користувача класу
	//В середині класу, буде ще 1 клас для зберігання інформації
	class Node //Вузлик списку - зберігає дані 
	{
	public:
		MyData data; // сам об'єкт, який зберігає вузол (наприклад, один People)
		Node* next; // вказівник на наступний вузол списку (наступний елемент)
	};
	Node* head; // вказівник на перший вузол списку. Якщо список пустий, то head = NULL

public:
	MyList() // конструктор списку
	{
		head = NULL; // одразу після створення список порожній - вказівник нікуди не веде
	}
	
	void Add(MyData data) // метод додавання нового елемента у кінець списку
	{
		if (head == NULL) // якщо список ще пустий
		{
			Node* node = new Node; // виділяємо пам'ять під новий вузол
			node->data = data; // записуємо у вузол передані дані
			node->next = NULL; // наступного елемента ще немає
			head = node; // цей вузол стає першим (і єдиним) елементом списку
		}
		else // якщо у списку вже є хоча б один елемент
		{
			//Додавання елемента у кінець списку
			//0.Стоврити новий елемент
			Node* node = new Node; // створюємо новий вузол
			node->data = data; // зберігаємо у ньому дані
			node->next = NULL; // він буде останнім, тому next = NULL
			//1.Треба піти у кінець списку
			Node* end = head; // починаємо рух з початку списку
			while (end->next != NULL) // йдемо, поки не дійдемо до вузла, у якого немає наступного
				end = end->next; // переходимо до наступного вузла
			//2.і тоді новий елемент додати у кінець списку
			end->next = node; // "прив'язуємо" новий вузол до останнього елемента списку
		}
	}

	void ShowItems() // виводить усі елементи списку на екран
	{
		Node* temp = head; // допоміжний вказівник, щоб не втратити head під час обходу
		while (temp != NULL) // поки не дійшли до кінця списку
		{
			cout << temp->data << "\n"; // виводимо дані поточного вузла (викликається operator<< того типу, що зберігається)
			temp = temp->next; // переходимо до наступного вузла
		}
	}

	int Size() // повертає кількість елементів у списку
	{
		int count = 0; // лічильник елементів, спочатку 0
		Node* temp = head; // допоміжний вказівник для обходу
		while (temp != NULL) // поки не дійшли до кінця
		{
			count++; // збільшуємо лічильник на кожному вузлі
			temp = temp->next; // рухаємось далі по списку
		}
		return count; // повертаємо підсумкову кількість
	}

	void Sort() // сортує список методом "бульбашки" (порівнюючи сусідів)
	{
		int n = this->Size(); // спершу дізнаємось скільки всього елементів
		Node* temp = head; // temp вказує на елемент, "на позицію якого" шукаємо найменший
		for (int i = 0; i < n - 1; i++) // зовнішній цикл - для кожної позиції у списку, крім останньої
		{
			Node* next = temp->next; // next починає рух з елемента одразу після temp
			for (int j = i + 1; j < n; j++) // внутрішній цикл - порівнюємо temp з усіма елементами після нього
			{
				if (temp->data>next->data) // якщо елемент temp "більший" за next (використовує operator> з People)
				{
					MyData tempData = temp->data; // зберігаємо дані temp у тимчасову змінну
					temp->data = next->data; // у temp записуємо дані next
					next->data = tempData; //переставляємо елементи місцями
				}
				next = next->next; //переходимо на наступний у списку
			}
			temp = temp->next; // після завершення внутрішнього циклу зсуваємо temp на позицію далі
		}
	}

	void WriteFile(string fileName) // записує весь список у текстовий файл
	{
		ofstream outFile(fileName); // відкриваємо (створюємо) файл для запису з переданою назвою
		Node* temp = head; // допоміжний вказівник для обходу списку
		while (temp != NULL) // поки не дійшли до кінця списку
		{
			outFile << temp->data << "\n"; // записуємо дані вузла у файл (викликається operator<< для ofstream)
			temp = temp->next; // переходимо до наступного вузла
		}
	}
};
