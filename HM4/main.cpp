void menu() // функція, що показує меню і обробляє вибір користувача
{
	MyList<People> items; // створюємо порожній список, який зберігатиме об'єкти People
	int action = 0; // змінна для збереження вибору користувача, 0 = ще не вибрано (умова для входу в цикл)
	do // цикл "робити, поки" - виконається хоча б один раз
	{
		cout << "Оберіть операцію:\n"; // виводимо меню
		cout << "0.Вихід\n";
		cout << "1.Додати нового\n";
		cout << "2.Показати усіх козаків\n";
		cout << "3.Сортувати список\n";
		cout << "4.Записати у файл\n";
		cout << "->_"; // запрошення до вводу
		cin >> action; // зчитуємо номер дії від користувача
		cin.ignore(); // чистимо буфер вводу (прибираємо символ переносу рядка після cin >> action)
		switch (action) // обираємо гілку залежно від введеної дії
		{
		case 1: // додавання нового елемента
		{
			string name, phone; // локальні змінні для введених даних
			int age;
			cout << "Вкажіть ПІБ: "; // просимо ввести ім'я
			getline(cin, name); // зчитуємо весь рядок (ім'я може містити пробіли)
			cout << "Вкажіть телефон: "; // просимо ввести телефон
			getline(cin, phone); // зчитуємо телефон
			cout << "Вкажіть вік: "; // просимо ввести вік
			cin >> age; // зчитуємо число
			items.Add(People(name, phone, age)); // створюємо тимчасовий об'єкт People і додаємо його у список
			break; // завершуємо цю гілку switch
		}
		case 2: // показ усіх елементів
		{
			cout << "---------Ваші козаки і козачки :)----------\n"; // заголовок
			items.ShowItems(); // виводимо весь список на екран
			break;
		}
		case 3: // сортування списку
		{
			items.Sort(); // виконуємо сортування
			cout << "----Список відсортовано :)-----\n"; // повідомлення про успіх
			break;
		}
		case 4: // запис списку у файл
		{
			string fileName; // назва файлу, яку введе користувач
			cout << "Вкажіть назву файлу: ";
			getline(cin, fileName); // зчитуємо назву файлу цілим рядком
			items.WriteFile(fileName); // записуємо весь список у вказаний файл
			cout << "-----Користувачі у файлі" << fileName << "------\n"; // повідомлення про успіх
			break; // завершуємо гілку (у вихідному коді break тут був відсутній - це небезпечно, тому додано)
		}
		}

	} while (action != 0); // повторюємо цикл, поки користувач не введе 0 (вихід)
}

void sortInt() // допоміжна функція - демонстрація сортування звичайного масиву int (не пов'язана з класами)
{
	int list[5] = { 12, 33, 4, 1, 8 }; // тестовий масив із 5 чисел
	int n = 5; // кількість елементів у масиві
	cout << "Список елементів\n";
	for (int i = 0; i < n; i++) // виводимо масив до сортування
	{
		cout << list[i] << "\t";
	}
	cout << "\n";
	//сортую список
	for (int i = 0; i < n - 1; i++) //іду до n-1
	{
		for (int j = i + 1; j < n; j++) //на i позицію буде ставити найменший
		{
			if (list[i] > list[j]) // якщо поточний елемент більший за наступний
			{
				int temp = list[i]; // зберігаємо значення
				list[i] = list[j]; // міняємо місцями
				list[j] = temp; //переставляємо елементи місцями
			}
		}
	}
	cout << "Сортований список елементів\n";
	for (int i = 0; i < n; i++) // виводимо масив після сортування
	{
		cout << list[i] << "\t";
	}
}
