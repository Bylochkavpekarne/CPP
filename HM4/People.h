#pragma once // вказує компілятору підключити цей файл лише один раз, навіть якщо він включений у кількох місцях

#include<iostream> // підключаємо бібліотеку для роботи з cout, cin, ostream
#include<fstream>  // підключаємо бібліотеку для роботи з файлами (ofstream, ifstream)
using namespace std; // щоб не писати std:: перед cout, string і т.д.

class People // оголошуємо клас "Людина" - модель даних, яку буде зберігати список
{
private: // ці поля доступні лише всередині самого класу People
	string name;  // ПІБ людини
	string phone; // Телефон людини
	int age;      // Вік людини

public: // ці методи і конструктори доступні ззовні класу
	People() // конструктор за замовчуванням - викликається, коли створюють People без параметрів
	{
		this->name = "Не вказано";  // задаємо значення за замовчуванням для імені
		this->phone = "+380";       // задаємо значення за замовчуванням для телефону
		this->age = 18;             // задаємо значення за замовчуванням для віку
	}
	People(const char* name, const char* phone, int age) // конструктор, що приймає C-рядки (символьні масиви)
	{
		this->name = name;   // копіюємо ім'я у поле класу (C-рядок автоматично конвертується у string)
		this->phone = phone; // копіюємо телефон у поле класу
		this->age = age;     // копіюємо вік у поле класу
	}
	People(const string name, const string phone, int age) // конструктор, що приймає готові об'єкти string
	{
		this->name = name;   // зберігаємо ім'я
		this->phone = phone; // зберігаємо телефон
		this->age = age;     // зберігаємо вік
	}

	friend ostream& operator<<(ostream& os, const People& people) // дружня функція - дозволяє писати cout << людина
	{
		os << people.name << "\t" << people.phone << "\t" // виводимо ім'я, потім телефон через табуляцію
			<< people.age; // виводимо вік
		return os; // повертаємо потік, щоб можна було "ланцюжком" виводити далі (наприклад, << "\n")
	}

	friend ofstream& operator<<(ofstream& os, const People& people) // окрема версія оператора саме для запису у файл
	{
		os << people.name << "\n" << people.phone << "\n" // у файл пишемо кожне поле з нового рядка (не через таб)
			<< people.age; // дописуємо вік
		return os; // повертаємо файловий потік для можливого продовження запису
	}
	//people - це об'єкт - який буде з правого боку від >
	bool operator>(const People& people) // оператор порівняння "більше" - потрібен для сортування списку
	{
		if (this->name > people.name) // порівнюємо імена як рядки (лексикографічно, за алфавітом)
			return true; // якщо ім'я поточного об'єкта "більше" за алфавітом - повертаємо true
		return false; // інакше - false
	}
};
